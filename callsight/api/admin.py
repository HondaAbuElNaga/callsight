"""Admin routes (spec 2026-11-15-agent-supervisor): users, settings, admin log, delete one call's content.

Decision 8: only the admin manages users; the web page manages supervisor and agent accounts only (admin accounts
stay on the command line, so the web page can never lock out the last admin). Users are disabled, never deleted.
Passwords are generated by the server, returned once and never logged.
No `from __future__ import annotations`: the route signatures use Annotated types passed in at runtime.
"""
import json
import logging
from datetime import date, datetime, timezone
from pathlib import Path

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, ConfigDict, Field, StrictBool, StrictInt
from sqlalchemy import select
from sqlalchemy.orm import Session

from .. import followups as fu
from ..db.models import AdminLog, AppUser, Call, GoldClip
from . import auth

log_ = logging.getLogger(__name__)
WEB_ROLES = ("supervisor", "agent")
LOG_LIMIT = 200


class UserIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    username: str = Field(min_length=1, max_length=50)
    role: str
    ext: str | None = Field(default=None, pattern=r"^\d{1,6}$")


class UserPatch(BaseModel):
    model_config = ConfigDict(extra="forbid")
    role: str | None = None
    ext: str | None = Field(default=None, pattern=r"^\d{1,6}$")
    clear_ext: StrictBool = False
    active: StrictBool | None = None


class SettingsIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    followup_start: date | None = None
    followup_kpi_since: date | None = None


class DeleteIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    reason: str = Field(min_length=5, max_length=300)
    confirm: StrictInt               # the admin types the call number


def drop_draft(path: Path, name: str) -> None:
    """The gold set's machine drafts file holds transcript text per clip: remove the erased clip's entry."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return
    if isinstance(data, dict) and data.pop(name, None) is not None:
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
        tmp.replace(path)


def _now() -> datetime:
    return datetime.now(timezone.utc)


def user_dict(u: AppUser, now: datetime) -> dict:
    return {"id": u.id, "username": u.username, "role": u.role, "ext": u.ext, "active": u.active,
            "locked": bool(u.locked_until and u.locked_until > now),
            "created_at": u.created_at.isoformat() if u.created_at else None}


def register(app: FastAPI, *, DB, Admin, cfg) -> None:

    def log(s: Session, user: AppUser, action: str, target: str, reason: str | None = None) -> None:
        s.add(AdminLog(user_id=user.id, action=action, target=target[:100], reason=reason, at=_now()))

    def web_user(s: Session, user_id: int, me: AppUser) -> AppUser:
        u = s.get(AppUser, user_id)
        if u is None:
            raise HTTPException(404, "no such user")
        if u.id == me.id:
            raise HTTPException(403, "you cannot change your own account here")
        if u.role not in WEB_ROLES:
            raise HTTPException(403, "admin accounts are managed on the command line")
        return u

    def check_ext(s: Session, role: str, ext: str | None, user_id: int | None = None) -> None:
        try:
            auth._check_agent_ext(role, ext, set(cfg.teams().ext_team))    # noqa: SLF001 - one rule for CLI + web
        except ValueError as exc:
            raise HTTPException(422, str(exc)) from None
        if role == "agent" and ext:
            other = s.scalars(select(AppUser).where(AppUser.role == "agent", AppUser.active.is_(True),
                                                    AppUser.ext == ext, AppUser.id != (user_id or 0))).first()
            if other is not None:
                raise HTTPException(409, f"extension {ext} already belongs to agent {other.username}")

    # ---------- users ----------

    @app.get("/api/admin/users")
    def users(user: Admin, s: DB) -> list[dict]:
        now = _now()
        return [user_dict(u, now) for u in s.scalars(select(AppUser).order_by(AppUser.role, AppUser.username))]

    @app.post("/api/admin/users")
    def create(body: UserIn, user: Admin, s: DB) -> dict:
        if body.role not in WEB_ROLES:
            raise HTTPException(422, "role must be supervisor or agent")
        check_ext(s, body.role, body.ext)
        password = auth.generate_password()
        try:
            u = auth.create_user(s, body.username, password, body.role, body.ext, set(cfg.teams().ext_team))
        except ValueError as exc:
            s.rollback()
            raise HTTPException(422, str(exc)) from None
        log(s, user, "create_user", f"{u.username} ({u.role})")
        s.commit()
        return {**user_dict(u, _now()), "password": password}     # shown once on the page

    @app.patch("/api/admin/users/{user_id}")
    def change(user_id: int, body: UserPatch, user: Admin, s: DB) -> dict:
        u = web_user(s, user_id, user)
        role = body.role or u.role
        if role not in WEB_ROLES:
            raise HTTPException(422, "role must be supervisor or agent")
        ext = None if body.clear_ext else (body.ext if body.ext is not None else u.ext)
        changed = []
        if role != u.role or ext != u.ext:
            check_ext(s, role, ext, u.id)
            changed.append(f"role={role} ext={ext or '-'}")
            u.role, u.ext = role, ext
        if body.active is not None and body.active != u.active:
            if body.active and u.role == "agent":
                check_ext(s, u.role, u.ext, u.id)
            u.active = body.active
            changed.append("enabled" if body.active else "disabled")
        if changed:
            u.token_version += 1                 # open logins end: scope and role must never be stale
            log(s, user, "change_user", f"{u.username}: {', '.join(changed)}")
            s.commit()
        return user_dict(u, _now())

    @app.post("/api/admin/users/{user_id}/password")
    def reset_password(user_id: int, user: Admin, s: DB) -> dict:
        u = web_user(s, user_id, user)
        password = auth.generate_password()
        auth.set_password(s, u.username, password)      # +1 token_version, unlock
        log(s, user, "reset_password", u.username)
        s.commit()
        return {"id": u.id, "username": u.username, "password": password}

    # ---------- settings ----------

    def settings_dict(s: Session) -> dict:
        return {k: v.isoformat() if v else None for k, v in fu.settings(s).items()}

    @app.get("/api/admin/settings")
    def get_settings(user: Admin, s: DB) -> dict:
        return settings_dict(s)

    @app.put("/api/admin/settings")
    def put_settings(body: SettingsIn, user: Admin, s: DB) -> dict:
        old = fu.settings(s)
        for key, value in ((fu.SETTING_START, body.followup_start), (fu.SETTING_KPI, body.followup_kpi_since)):
            if value is not None and not date(2020, 1, 1) <= value <= date(2100, 1, 1):
                raise HTTPException(422, "bad date")
            if old[key] != value:
                fu.set_setting(s, key, value, user.id)
                log(s, user, "setting", f"{key}={value.isoformat() if value else '-'}")
        s.commit()
        return settings_dict(s)

    # ---------- admin log ----------

    @app.get("/api/admin/log")
    def admin_log(user: Admin, s: DB) -> list[dict]:
        names = dict(s.execute(select(AppUser.id, AppUser.username)).all())
        rows = s.scalars(select(AdminLog).order_by(AdminLog.at.desc(), AdminLog.id.desc()).limit(LOG_LIMIT))
        return [{"id": r.id, "user": names.get(r.user_id, ""), "action": r.action, "target": r.target,
                 "reason": r.reason, "at": r.at.isoformat()} for r in rows]

    # ---------- delete one call's content (decision 7) ----------

    @app.post("/api/calls/{call_id}/delete-content")
    def delete_content(call_id: int, body: DeleteIn, user: Admin, s: DB) -> dict:
        from .. import retention
        c = s.get(Call, call_id)
        if c is None:
            raise HTTPException(404, "no such call")
        if body.confirm != c.id:
            raise HTTPException(422, "type the call number to confirm")
        reason = body.reason.strip()
        if len(reason) < 5:
            raise HTTPException(422, "write a reason (5 characters or more)")
        if c.content_deleted_at is not None:
            raise HTTPException(409, "already deleted")
        rel = c.recording_path
        what, _, _ = retention.erase_call_content(s, c, cfg.audio_dir, None, None)
        for clip in s.scalars(select(GoldClip).where(GoldClip.call_id == c.id)):
            root = cfg.audio_dir.resolve()
            p = (root / clip.file).resolve()
            if p.is_relative_to(root) and p != root and p.is_file():
                p.unlink()
            s.delete(clip)
            drop_draft(cfg.audio_dir / "goldset" / "drafts.json", Path(clip.file).name)
            what.append("gold_clip")
        c.content_deleted_at = _now()
        log(s, user, "delete_call_content", f"call:{c.id} {','.join(what) or 'nothing'}"[:100], reason)
        s.commit()
        if rel and cfg.delete_backup_copy is not None:
            try:
                cfg.delete_backup_copy(c.id, rel)       # worker task: BACKUP_DIR is read-only in the API
            except Exception:  # noqa: BLE001 - never fail the delete; ids only in the log
                log_.warning("call %s: backup-copy delete task not sent; remove it by hand", c.id)
        return {"ok": True, "deleted": what}
