"""Score the benchmark: typed gold-set texts (DB) + model hypotheses (data/asr-bench/<model>.jsonl) -> docs/asr-benchmark.md

    python -m callsight goldset score [--bench-dir data/asr-bench] [--out docs/asr-benchmark.md]

Pure functions here (tested); the CLI only loads the DB rows and writes the file.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from .metrics import Score
from .normalize import prepare

WER_TARGET = 0.25                       # mission success metric
NOTES = {
    "jais-asr-4bit": "official 4-bit (W4A16 AWQ) weights; bf16 needs ~12 GB (server)",
    "audar-asr-turbo": "AudarAI Community License: check before production use",
    "whisper-large-v3": "MIT licence",
}


def load_hypotheses(path: Path) -> dict[str, dict]:
    """clip file name -> last record for it (a re-run line wins). Broken lines are skipped."""
    out: dict[str, dict] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        try:
            rec = json.loads(line)
            out[rec["clip"]] = rec
        except (ValueError, KeyError, TypeError):
            continue
    return out


def failure_kind(reference: str, hypothesis: str) -> str | None:
    """'empty', 'truncated' (< 40% of the reference words) or 'repeated' (one word or bigram fills > 30%)."""
    hw, rw = prepare(hypothesis), prepare(reference)
    if not hw:
        return "empty"
    if rw and len(hw) < 0.4 * len(rw):
        return "truncated"
    if len(hw) >= 10:
        grams = hw + [" ".join(p) for p in zip(hw, hw[1:])]
        top = max(grams.count(g) for g in set(grams))
        if top > 0.3 * len(hw):
            return "repeated"
    return None


@dataclass
class ModelResult:
    model: str
    clips: int = 0                                   # clips with a typed reference and a hypothesis
    missing: int = 0                                 # typed clips the model has no line for
    errors: int = 0
    score: Score = field(default_factory=Score)
    audio_s: float = 0.0
    run_s: float = 0.0
    peak_gpu_mb: int = 0
    failures: dict[str, int] = field(default_factory=dict)

    @property
    def rtf(self) -> float:                          # seconds of compute per second of audio (lower = faster)
        return self.run_s / self.audio_s if self.audio_s else 0.0


def score_model(model: str, refs: dict[str, str], hyps: dict[str, dict]) -> ModelResult:
    r = ModelResult(model)
    for clip, ref in sorted(refs.items()):
        rec = hyps.get(clip)
        if rec is None:
            r.missing += 1
            continue
        text = rec.get("text") or ""
        r.clips += 1
        r.errors += "error" in rec
        r.score.add(ref, text)
        r.audio_s += float(rec.get("audio_s") or 0)
        r.run_s += float(rec.get("seconds") or 0)
        r.peak_gpu_mb = max(r.peak_gpu_mb, int(rec.get("peak_gpu_mb") or 0))
        kind = failure_kind(ref, text)
        if kind:
            r.failures[kind] = r.failures.get(kind, 0) + 1
    return r


def winner(results: list[ModelResult], total: int) -> ModelResult | None:
    """Lowest WER among models that ran every typed clip and reach the target."""
    ok = [r for r in results if r.clips == total and total and r.score.wer <= WER_TARGET]
    return min(ok, key=lambda r: r.score.wer) if ok else None


def render(results: list[ModelResult], refs: dict[str, str], hyps_by_model: dict[str, dict[str, dict]],
           total_clips: int, examples: int = 3) -> str:
    typed = len(refs)
    lines = ["# ASR benchmark on our own calls", "",
             f"Gold set: {total_clips} clips × 60 s (mono 8 kHz phone audio, both speakers); "
             f"**{typed} / {total_clips} typed**. Scored after `echonova-v1` normalisation, corpus-level WER/CER.",
             "Generated by `python -m callsight goldset score` — do not edit by hand.", ""]
    if typed < total_clips:
        lines += [f"> ⚠ Only {typed} of {total_clips} reference texts are typed: numbers below are provisional.", ""]
    lines += ["| Model | Clips | WER | CER | Speed (RTF) | Peak GPU | Failures | Note |",
              "|---|---|---|---|---|---|---|---|"]
    for r in sorted(results, key=lambda r: (r.clips == 0, r.score.wer)):
        fails = ", ".join(f"{k} {v}" for k, v in sorted(r.failures.items())) or "-"
        if r.errors:
            fails += f"; errors {r.errors}"
        clips = f"{r.clips}/{typed}" + (f" ({r.missing} not run)" if r.missing else "")
        wer = f"{r.score.wer:.1%}" if r.clips else "-"
        cer = f"{r.score.cer:.1%}" if r.clips else "-"
        lines.append(f"| {r.model} | {clips} | {wer} | {cer} | {r.rtf:.2f} | {r.peak_gpu_mb / 1024:.1f} GB | {fails} | "
                     f"{NOTES.get(r.model, '')} |")
    lines += ["", "RTF = compute seconds per second of audio on this PC (RTX 5050 Laptop, 8 GB), lower is faster.", ""]

    best = winner(results, typed)
    lines.append("## Result")
    lines.append("")
    if typed < total_clips:
        lines.append("No winner yet: wait until all reference texts are typed.")
    elif best:
        lines.append(f"**Winner: {best.model}**, WER {best.score.wer:.1%} (target ≤ {WER_TARGET:.0%}). "
                     f"Set `ASR_MODEL={best.model}` in `.env` to use it for all calls.")
    else:
        lines.append(f"**No model reaches WER ≤ {WER_TARGET:.0%}** on our calls. Options: fine-tune the best model on our "
                     "own calls, or test again on the server with full-precision weights.")
    lines.append("")

    lines += ["## Examples", ""]
    for clip in sorted(refs)[:examples]:
        lines += [f"### {clip}", "", f"- **Reference:** {refs[clip]}"]
        for r in results:
            rec = hyps_by_model.get(r.model, {}).get(clip)
            if rec is not None:
                lines.append(f"- **{r.model}:** {rec.get('text') or '(empty)'}")
        lines.append("")
    return "\n".join(lines)


def build_report(refs: dict[str, str], bench_dir: Path, total_clips: int) -> tuple[str, list[ModelResult]]:
    hyps_by_model = {p.stem: load_hypotheses(p) for p in sorted(bench_dir.glob("*.jsonl"))}
    results = [score_model(m, refs, h) for m, h in hyps_by_model.items()]
    return render(results, refs, hyps_by_model, total_clips), results
